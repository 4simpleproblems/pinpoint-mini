(function() {
    if (typeof window === 'undefined') return;

    // Track current page state inside about:blank
    if (!window.__CURRENT_PAGE__) {
        const path = window.location.pathname;
        if (path === '' || path === '/' || path.endsWith('index.html') || path.endsWith('home.html')) {
            window.__CURRENT_PAGE__ = 'home.html';
        } else {
            window.__CURRENT_PAGE__ = path;
        }
    }

    // Ensure base tag is present for relative resource resolution
    function ensureBaseTag() {
        if (!document.head) return;
        let base = document.querySelector('base');
        if (!base) {
            base = document.createElement('base');
            const origin = localStorage.getItem('pinpoint_entry_origin') || window.location.origin;
            base.href = origin.endsWith('/') ? origin : origin + '/';
            document.head.insertBefore(base, document.head.firstChild);
        }
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', ensureBaseTag);
    } else {
        ensureBaseTag();
    }

    // Function to navigate inside about:blank without changing window location
    window.navigateToAboutBlankPage = async function(targetUrl) {
        if (!targetUrl || window.__IS_PANIC_TRIGGERED__ || (window.top && window.top.__IS_PANIC_TRIGGERED__)) return;

        // Strip leading # (for hash-style hrefs generated by tab-disguiser)
        if (targetUrl.startsWith('#')) {
            targetUrl = targetUrl.substring(1);
        }

        // Unwrap redirect.html?target=...
        if (targetUrl.includes('redirect.html') && targetUrl.includes('target=')) {
            try {
                const urlObj = new URL(targetUrl, window.location.origin);
                const tParam = urlObj.searchParams.get('target');
                if (tParam) {
                    targetUrl = tParam;
                }
            } catch(e) {
                const match = targetUrl.match(/target=([^&]+)/);
                if (match && match[1]) targetUrl = decodeURIComponent(match[1]);
            }
        }
        
        // Normalize sidebar / Google Classroom links to home.html
        if (targetUrl.includes('classroom.google.com') ||
            targetUrl.endsWith('/index.html') ||
            targetUrl === '/index.html' ||
            targetUrl === 'index.html' ||
            targetUrl === './index.html' ||
            targetUrl === '../index.html' ||
            targetUrl === '/' ||
            targetUrl === '') {
            targetUrl = 'home.html';
        }

        // Strip leading ./ and ../ so fetch resolves cleanly from the root base
        while (targetUrl.startsWith('./') || targetUrl.startsWith('../')) {
            if (targetUrl.startsWith('./')) {
                targetUrl = targetUrl.substring(2);
            } else if (targetUrl.startsWith('../')) {
                targetUrl = targetUrl.substring(3);
            }
        }

        if (targetUrl.startsWith('/')) {
            targetUrl = targetUrl.substring(1);
        }

        try {
            const origin = localStorage.getItem('pinpoint_entry_origin') || window.location.origin;
            let fullUrl = targetUrl;
            if (!targetUrl.startsWith('http://') && !targetUrl.startsWith('https://')) {
                fullUrl = new URL(targetUrl, origin.endsWith('/') ? origin : origin + '/').href;
            }

            const res = await fetch(fullUrl);
            if (!res.ok) throw new Error('Fetch failed: ' + res.status);
            let html = await res.text();

            // Inject base tag and page state + self-perpetuating navigateToAboutBlankPage
            const baseTag = '<base href="' + (origin.endsWith('/') ? origin : origin + '/') + '">';
            const navFn = window.navigateToAboutBlankPage.toString();
            const pageScript = '<script>window.__CURRENT_PAGE__ = ' + JSON.stringify(targetUrl) + ';window.navigateToAboutBlankPage = ' + navFn + ';<' + '/script>';

            // If navigating to a game/textbook, guarantee the tab title stays disguised
            let titleGuard = '';
            if (targetUrl.includes('textbooks/') || targetUrl.includes('.html')) {
                try {
                    const cfgRaw = localStorage.getItem('pinpoint_classroom_config');
                    const cfgObj = cfgRaw ? JSON.parse(cfgRaw) : {};
                    const curName = (cfgObj.history || cfgObj.english || {}).name || 'World History';
                    const isHistoryStream = targetUrl.includes('history.html') && !targetUrl.includes('classwork');
                    const disguiseTitle = isHistoryStream ? (curName + ' - Classroom') : ('Classwork for ' + curName + ' - Classroom');
                    if (html.includes('<title>')) {
                        html = html.replace(/<title>[\s\S]*?<\/title>/i, '<title>' + disguiseTitle + '</title>');
                    }
                    titleGuard = '<script>(function(){' +
                        'var locked = ' + JSON.stringify(disguiseTitle) + ';' +
                        'try {' +
                        '  var nd = Object.getOwnPropertyDescriptor(Document.prototype, "title");' +
                        '  Object.defineProperty(document, "title", {' +
                        '    configurable: true, enumerable: true,' +
                        '    get: function() { return locked; },' +
                        '    set: function() { if (nd && nd.set) nd.set.call(document, locked); }' +
                        '  });' +
                        '} catch(e){}' +
                        'var tg = document.querySelector("title");' +
                        'if (tg) { new MutationObserver(function() { if (tg.textContent !== locked) tg.textContent = locked; }).observe(tg, { childList: true, characterData: true, subtree: true }); }' +
                        'setInterval(function() { if (document.title !== locked) document.title = locked; }, 150);' +
                    '})();<' + '/script>';
                } catch(e) {}
            }

            if (html.includes('<head>')) {
                html = html.replace('<head>', '<head>' + baseTag + titleGuard + pageScript);
            } else {
                html = baseTag + titleGuard + pageScript + html;
            }

            window.__CURRENT_PAGE__ = targetUrl;
            document.open();
            document.write(html);
            document.close();
        } catch(err) {
            console.error('about:blank navigation error for', targetUrl, err);
        }
    };

    const isAboutBlank = (window.location.protocol === 'about:' || window.location.href === 'about:blank' || window.location.href.startsWith('about:'));

    if (isAboutBlank) {
        // Intercept TabDisguiser.openPopout so popouts load in about:blank instead of navigating top window
        // (set after DOMContentLoaded so TabDisguiser is defined by then)

        // Patch all navigation-style links directly on the DOM element so there's no URL for the browser to follow
        function patchNavigationLinks() {
            if (typeof window.TabDisguiser !== 'undefined') {
                window.TabDisguiser.openPopout = function(url, title) {
                    window.navigateToAboutBlankPage(url);
                    return null;
                };
            }

            document.querySelectorAll('a[href]').forEach(function(a) {
                var href = a.getAttribute('href');
                if (!href) return;
                // Skip bare anchors, javascript:, and external non-project URLs
                if (href === '#' || href.startsWith('javascript:') || href.startsWith('mailto:')) return;

                // Resolve what this link points to and handle it
                var targetUrl = href;

                // Strip leading hash (for tab-disguiser generated #page links)
                if (targetUrl.startsWith('#')) {
                    targetUrl = targetUrl.substring(1);
                }

                // Only patch links that point to our internal pages
                var isInternal = targetUrl.includes('.html') || targetUrl.startsWith('/') || targetUrl.startsWith('./') || targetUrl.startsWith('../') || targetUrl.includes('redirect.html') || targetUrl.includes('classroom.google.com');
                if (!isInternal) return;

                // Capture the resolved target now, remove nav attributes
                var captured = targetUrl;
                a.setAttribute('href', 'javascript:void(0)');
                a.removeAttribute('target');
                a.style.cursor = 'pointer';
                a.onclick = function(e) {
                    e.preventDefault();
                    e.stopPropagation();
                    window.navigateToAboutBlankPage(captured);
                    return false;
                };
            });

            // Also neutralize inline onclick navigation on non-anchor elements
            document.querySelectorAll('[onclick]').forEach(function(el) {
                var oc = el.getAttribute('onclick') || '';
                if (oc.includes('location.href') || oc.includes('location.replace') || oc.includes('location.assign') || oc.includes('redirect.html') || oc.includes('.html')) {
                    // Extract URL if it's a simple location.href = 'url' assignment
                    var match = oc.match(/location\.href\s*=\s*['"]([^'"]+)['"]/);
                    if (match) {
                        var captured = match[1];
                        el.removeAttribute('onclick');
                        el.style.cursor = 'pointer';
                        el.onclick = function(e) {
                            e.preventDefault();
                            e.stopPropagation();
                            window.navigateToAboutBlankPage(captured);
                            return false;
                        };
                    } else {
                        el.removeAttribute('onclick');
                    }
                }
            });
        }

        // Run once DOM is ready, then watch for dynamic changes
        function setupLinkPatching() {
            patchNavigationLinks();
            // MutationObserver to catch dynamically-injected nav (tab-disguiser, etc.)
            if (typeof MutationObserver !== 'undefined') {
                var observer = new MutationObserver(function(mutations) {
                    var needsPatch = false;
                    mutations.forEach(function(m) {
                        if (m.addedNodes.length) needsPatch = true;
                    });
                    if (needsPatch) patchNavigationLinks();
                });
                observer.observe(document.body || document.documentElement, { childList: true, subtree: true });
            }
        }

        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', setupLinkPatching);
        } else {
            setupLinkPatching();
        }

        // Intercept global link and element clicks
        document.addEventListener('click', function(e) {
            if (window.__IS_PANIC_TRIGGERED__ || (window.top && window.top.__IS_PANIC_TRIGGERED__)) return;
            let anchor = e.target.closest('a');
            let clickable = anchor || e.target.closest('[data-href], [onclick], .game-row, .uTwgne, .slDfNd');
            
            let target = null;
            if (anchor) {
                target = anchor.getAttribute('href');
                // Remove target="_top" or target="_self" so it doesn't break out of about:blank
                if (anchor.getAttribute('target') === '_top') {
                    anchor.removeAttribute('target');
                }
            } else if (clickable) {
                target = clickable.getAttribute('data-href');
            }

            if (!target || target.startsWith('javascript:')) return;

            // Intercept hash-style links (e.g. #pages/history.html) generated in about:blank mode
            if (target.startsWith('#')) {
                const stripped = target.substring(1);
                if (!stripped) return; // bare # anchor, ignore
                e.preventDefault();
                e.stopPropagation();
                window.navigateToAboutBlankPage(stripped);
                return;
            }

            // If it's any page link or classroom redirect:
            if (target.includes('classroom.google.com') || target.includes('redirect.html') || target.endsWith('home.html') || target.endsWith('index.html') || target.includes('.html') || target.startsWith('/') || target.startsWith('./') || target.startsWith('../')) {
                e.preventDefault();
                e.stopPropagation();
                window.navigateToAboutBlankPage(target);
            }
        }, true);

        // Listen for panic messages so top about:blank window exits cleanly
        window.addEventListener('message', function(e) {
            if (e.data === 'panic' || (e.data && e.data.type === 'panic')) {
                window.__IS_PANIC_TRIGGERED__ = true;
                const targetUrl = (e.data && e.data.url) || localStorage.getItem('pinpoint_panic_url') || 'https://classroom.google.com/';
                if (window.__originalLocationReplace) {
                    try {
                        window.__originalLocationReplace.call(window.location, targetUrl);
                        return;
                    } catch(err) {}
                }
                if (window.__origLocationHrefSet) {
                    try {
                        window.__origLocationHrefSet.call(window.location, targetUrl);
                        return;
                    } catch(err) {}
                }
                try {
                    window.location.href = targetUrl;
                    return;
                } catch(err) {}
                try {
                    window.location.replace(targetUrl);
                    return;
                } catch(err) {}
            }
        });

        // Override location navigation functions in about:blank
        try {
            const originalReplace = window.location.replace;
            window.__originalLocationReplace = originalReplace;
            window.location.replace = function(url) {
                if (!window.__IS_PANIC_TRIGGERED__ && (!window.top || !window.top.__IS_PANIC_TRIGGERED__) && url && (url.includes('classroom.google.com') || url.includes('redirect.html') || url.includes('.html') || url.startsWith('/') || url.startsWith('./'))) {
                    window.navigateToAboutBlankPage(url);
                } else if (originalReplace) {
                    originalReplace.call(window.location, url);
                }
            };
            const originalAssign = window.location.assign;
            window.__originalLocationAssign = originalAssign;
            window.location.assign = function(url) {
                if (!window.__IS_PANIC_TRIGGERED__ && (!window.top || !window.top.__IS_PANIC_TRIGGERED__) && url && (url.includes('classroom.google.com') || url.includes('redirect.html') || url.includes('.html') || url.startsWith('/') || url.startsWith('./'))) {
                    window.navigateToAboutBlankPage(url);
                } else if (originalAssign) {
                    originalAssign.call(window.location, url);
                }
            };

            // Intercept window.location.href = "..." assignments (used by inline onclicks)
            try {
                const locDescriptor = Object.getOwnPropertyDescriptor(window.location, 'href') ||
                                      Object.getOwnPropertyDescriptor(Location.prototype, 'href');
                if (locDescriptor && locDescriptor.set) {
                    const origSet = locDescriptor.set;
                    window.__origLocationHrefSet = origSet;
                    Object.defineProperty(window.location, 'href', {
                        get: locDescriptor.get,
                        set: function(url) {
                            if (!window.__IS_PANIC_TRIGGERED__ && (!window.top || !window.top.__IS_PANIC_TRIGGERED__) && url && typeof url === 'string' && (url.includes('.html') || url.startsWith('/') || url.startsWith('./') || url.includes('classroom.google.com') || url.includes('redirect.html'))) {
                                window.navigateToAboutBlankPage(url);
                            } else {
                                origSet.call(window.location, url);
                            }
                        },
                        configurable: true
                    });
                }
            } catch(e2) {
                // location.href override not supported — fall back to DOMContentLoaded cleanup
            }
        } catch(e) {}

        // After DOM is ready, remove all inline onclick attributes that navigate the page
        function patchInlineOnclicks() {
            document.querySelectorAll('[onclick]').forEach(function(el) {
                const oc = el.getAttribute('onclick') || '';
                if (oc.includes('location.href') || oc.includes('location.replace') || oc.includes('location.assign')) {
                    el.removeAttribute('onclick');
                }
            });
        }
        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', patchInlineOnclicks);
        } else {
            patchInlineOnclicks();
        }
    }
})();
